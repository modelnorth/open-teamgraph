import { IGraphStore } from "../../../core/src/graph/store";
import { ExpertFinder, ExpertScore } from "../../../core/src/algorithms/expert-finder";
import { BlastRadiusAnalyzer, BlastRadiusResult } from "../../../core/src/algorithms/blast-radius";

export interface PRReviewerReport {
  targetFiles: string[];
  recommendedReviewers: ExpertScore[];
  affectedServices: string[];
  affectedTeams: string[];
  relatedTasks: string[];
  markdownComment: string;
}

export class PRReviewerBot {
  private store: IGraphStore;
  private expertFinder: ExpertFinder;
  private blastAnalyzer: BlastRadiusAnalyzer;

  constructor(store: IGraphStore) {
    this.store = store;
    this.expertFinder = new ExpertFinder(store);
    this.blastAnalyzer = new BlastRadiusAnalyzer(store);
  }

  async generateReport(modifiedFiles: string[]): Promise<PRReviewerReport> {
    const reviewerScores = new Map<string, ExpertScore>();
    const affectedServices = new Set<string>();
    const affectedTeams = new Set<string>();
    const relatedTasks = new Set<string>();

    for (const filepath of modifiedFiles) {
      // Find matching File node in graph
      const matches = await this.store.queryNodes(
        n => n.type === "File" && (n.name === filepath || n.id.endsWith(`:${filepath}`) || n.properties?.path === filepath)
      );

      const targetNode = matches[0];
      if (targetNode) {
        // 1. Discover Experts
        const experts = await this.expertFinder.findExperts(targetNode.id, 3);
        for (const exp of experts) {
          const current = reviewerScores.get(exp.person.id);
          if (!current || exp.score > current.score) {
            reviewerScores.set(exp.person.id, exp);
          }
        }

        // 2. Discover Blast Radius
        const blast = await this.blastAnalyzer.analyze(targetNode.id, 2);
        if (blast) {
          blast.affectedServices.forEach(s => affectedServices.add(s.name));
          blast.owningTeams.forEach(t => affectedTeams.add(t.name));
          blast.dependentTasks.forEach(t => relatedTasks.add(t.name));
        }
      }
    }

    // Sort reviewers by score
    const topReviewers = Array.from(reviewerScores.values())
      .sort((a, b) => b.score - a.score)
      .slice(0, 4);

    // Format Markdown comment for PR
    const md = this.buildMarkdown(
      modifiedFiles,
      topReviewers,
      Array.from(affectedServices),
      Array.from(affectedTeams),
      Array.from(relatedTasks)
    );

    return {
      targetFiles: modifiedFiles,
      recommendedReviewers: topReviewers,
      affectedServices: Array.from(affectedServices),
      affectedTeams: Array.from(affectedTeams),
      relatedTasks: Array.from(relatedTasks),
      markdownComment: md,
    };
  }

  private buildMarkdown(
    files: string[],
    reviewers: ExpertScore[],
    services: string[],
    teams: string[],
    tasks: string[]
  ): string {
    const reviewerLines = reviewers.length > 0
      ? reviewers.map(r => `- **${r.person.name}** (Score: \`${r.score}\`) — ${r.commitCount} commits, ${r.reviewCount} reviews`).join("\n")
      : "_No historical experts identified for these specific files._";

    const serviceLines = services.length > 0
      ? services.map(s => `\`${s}\``).join(", ")
      : "_None detected directly._";

    const teamLines = teams.length > 0
      ? teams.map(t => `**${t}**`).join(", ")
      : "_No owning teams linked._";

    const taskLines = tasks.length > 0
      ? tasks.map(t => `- ${t}`).join("\n")
      : "_No linked upstream tasks._";

    return `## 🛡️ Open TeamGraph — Autonomous PR Review & Impact Analysis

### 🎯 Recommended Reviewers (Recency-Decayed Expertise)
${reviewerLines}

### ⚠️ Downstream Blast Radius & Ownership
* **Impacted Services**: ${serviceLines}
* **Responsible Teams**: ${teamLines}

### 📋 Linked Tasks & Context
${taskLines}

---
*Generated by [Open TeamGraph](https://github.com/open-teamgraph) — the open-source engineering intelligence graph.*`;
  }
}
